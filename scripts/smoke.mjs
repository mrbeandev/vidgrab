const fixSrv = http.createServer((rq, rs) => {
  if (rq.url.includes("aes_001.ts") && !stalledOnce) {
    stalledOnce = true; // first request: send headers + a few bytes, then hang forever
    rs.writeHead(200, { "content-type": "video/mp2t", "content-length": 75968 });
    rs.write(Buffer.alloc(188, 0x47));
    console.log("   (fixture) stalling first request of aes_001.ts");
    return;
  }
  const path = decodeURIComponent(new URL(rq.url, "http://x").pathname.slice(1));
  if (path === "" || path === "index.html") {
    rs.writeHead(200, { "content-type": "text/html; charset=utf-8" });
    return rs.end(`<!doctype html><meta charset="utf-8"><title>VidGrab fixture page</title><h1>fixtures</h1><script>
      fetch('/aes.m3u8').then(r=>r.text()); fetch('/fmp4.m3u8').then(r=>r.text());
      fetch('/alt_ts/master.m3u8').then(r=>r.text()); fetch('/alt_fmp4/master.m3u8').then(r=>r.text());
      for (const f of ['src_videoonly.mp4','src_audioonly.m4a','src.webm']) { const v=document.createElement(f.endsWith('m4a')?'audio':'video'); v.src='/'+f; v.preload='auto'; v.muted=true; document.body.appendChild(v); v.load(); }
    </script>`);
  }
  const f = join(fixDir, path);
  if (!existsSync(f)) { rs.writeHead(404); return rs.end(); }
  const ct = f.endsWith(".m3u8") ? "application/vnd.apple.mpegurl" : f.endsWith(".ts") ? "video/mp2t" : f.endsWith(".key") ? "application/octet-stream" : f.endsWith(".m4a") ? "audio/mp4" : f.endsWith(".webm") ? "video/webm" : "video/mp4";
  const size = stat0(f).size;
  const range = /bytes=(\d*)-(\d*)/.exec(rq.headers.range || "");
  if (range && (range[1] || range[2])) {
    const start = range[1] ? parseInt(range[1], 10) : Math.max(0, size - parseInt(range[2], 10));
    const end = range[1] && range[2] ? Math.min(size - 1, parseInt(range[2], 10)) : size - 1;
    rs.writeHead(206, { "content-type": ct, "content-length": end - start + 1, "content-range": `bytes ${start}-${end}/${size}`, "accept-ranges": "bytes", "access-control-allow-origin": "*" });
    return createReadStream(f, { start, end }).pipe(rs);
  }
  rs.writeHead(200, { "content-type": ct, "content-length": size, "accept-ranges": "bytes", "access-control-allow-origin": "*" });
  if (rq.method === "HEAD") return rs.end();
  createReadStream(f).pipe(rs);
});
await new Promise((r) => fixSrv.listen(fixPort, "127.0.0.1", r));

