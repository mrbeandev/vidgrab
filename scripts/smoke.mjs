const req = (method, p) => new Promise((res, rej) => { const r = http.request({ host: "127.0.0.1", port, path: p, method }, (r) => { let b = ""; r.on("data", (c) => (b += c)); r.on("end", () => { try { res(JSON.parse(b)); } catch { rej(new Error(b)); } }); }); r.on("error", rej); r.end(); });
